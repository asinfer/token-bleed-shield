"""Generates token-efficient markdown contracts from environment snapshots."""

from pathlib import Path
from typing import Optional

from ..contract import CONTRACT_VERSION, ContractSnapshot, ToolchainContract, render_json_block
from .system_prober import EnvironmentSnapshot, ToolchainInfo


class ContractGenerator:
    """Renders machine-actionable pre-flight contracts for LLM agents.

    The rendered document serves two audiences at once: the prose sections are written for the
    agent's system prompt, while the embedded JSON block is the machine-readable form that
    guardrails parse.
    """

    @staticmethod
    def _toolchain_contract(toolchain: Optional[ToolchainInfo]) -> Optional[ToolchainContract]:
        if toolchain is None:
            return None
        return ToolchainContract(
            name=toolchain.name,
            version=toolchain.version,
            command_prefix=toolchain.command_prefix,
            forbidden=list(toolchain.forbidden_alternatives),
        )

    @classmethod
    def build_snapshot(cls, snapshot: EnvironmentSnapshot) -> ContractSnapshot:
        """Project an environment snapshot onto the machine-readable contract model."""
        return ContractSnapshot(
            contract_version=CONTRACT_VERSION,
            os_name=snapshot.os_name,
            os_release=snapshot.os_release,
            architecture=snapshot.architecture,
            primary_shell=snapshot.primary_shell,
            workspace_root=snapshot.workspace_root,
            git_branch=snapshot.git_branch,
            detected_project_files=list(snapshot.detected_project_files),
            python=cls._toolchain_contract(snapshot.python_toolchain),
            node=cls._toolchain_contract(snapshot.node_toolchain),
            rust=cls._toolchain_contract(snapshot.rust_toolchain),
        )

    @staticmethod
    def render_markdown(snapshot: EnvironmentSnapshot) -> str:
        lines = [
            "<!-- AUTO-GENERATED BY TOKEN BLEED SHIELD (PREVENTIVE AGENT CONTRACT) -->",
            "# HOST ENVIRONMENT CONTRACT",
            f"- **OS**: {snapshot.os_name} ({snapshot.architecture}) | Shell: `{snapshot.primary_shell}`",
            f"- **Workspace Root**: `{snapshot.workspace_root}`",
        ]

        if snapshot.git_branch:
            lines.append(f"- **Git Branch**: `{snapshot.git_branch}`")

        if snapshot.detected_project_files:
            files_str = ", ".join(f"`{f}`" for f in snapshot.detected_project_files)
            lines.append(f"- **Key Project Files**: {files_str}")

        lines.append("\n## Pinned Execution Directives")

        # Python directives
        if snapshot.python_toolchain and snapshot.python_toolchain.available:
            tc = snapshot.python_toolchain
            lines.append(f"### Python (`{tc.name}`)")
            if tc.version:
                lines.append(f"- Version: `{tc.version}`")
            if tc.command_prefix:
                lines.append(f"- Command Prefix: Execute all scripts via `{tc.command_prefix} <script>`")
            if tc.forbidden_alternatives:
                forb = ", ".join(f"`{a}`" for a in tc.forbidden_alternatives)
                lines.append(f"- **STRICT RULE**: NEVER invoke {forb} directly. Rely exclusively on `{tc.command_prefix}`.")

        # Node directives
        if snapshot.node_toolchain and snapshot.node_toolchain.available:
            tc = snapshot.node_toolchain
            lines.append(f"\n### JavaScript / Node (`{tc.name}`)")
            if tc.version:
                lines.append(f"- Version: `{tc.version}`")
            if tc.command_prefix:
                lines.append(f"- Command Prefix: Use `{tc.command_prefix}`")
            if tc.forbidden_alternatives:
                forb = ", ".join(f"`{a}`" for a in tc.forbidden_alternatives)
                lines.append(f"- **STRICT RULE**: DO NOT run {forb}.")

        # Rust directives
        if snapshot.rust_toolchain and snapshot.rust_toolchain.available:
            tc = snapshot.rust_toolchain
            lines.append(f"\n### Rust (`{tc.name}`)")
            lines.append(f"- Command Prefix: `{tc.command_prefix}`")

        lines.extend([
            "\n## Token Bleed Prevention Rules",
            "1. **Zero Path Reconnaissance**: Do NOT search filesystem for tool binaries (e.g. `which`, `where`, `find`).",
            "2. **Strict Cwd**: Run all operations relative to the workspace root without changing directories.",
            "3. **No Redundant Introspection**: Trust the directives above as immutable ground truth.",
        ])

        prose = "\n".join(lines)

        contract_snapshot = ContractGenerator.build_snapshot(snapshot)
        return f"{prose}\n\n## Machine-Readable Contract\n\n{render_json_block(contract_snapshot)}\n"

    @classmethod
    def write_contract(cls, snapshot: EnvironmentSnapshot, target_path: Optional[Path] = None) -> Path:
        out = target_path or (Path(snapshot.workspace_root) / ".agent-env.md")
        content = cls.render_markdown(snapshot)
        out.write_text(content, encoding="utf-8")
        return out
